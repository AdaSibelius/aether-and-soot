export function collectAllArchitectureFiles(rootDir: string): AstFileMetadata[] {
  const srcFiles = indexCodebaseAst(rootDir, true);
  const testScriptsDir = path.join(rootDir, 'tests/scripts');
  const toolFiles: AstFileMetadata[] = [];

  if (fs.existsSync(testScriptsDir)) {
    for (const name of fs.readdirSync(testScriptsDir)) {
      if (/\.(ts|tsx)$/.test(name)) {
        const full = path.join(testScriptsDir, name);
        const content = fs.readFileSync(full, 'utf-8');
        toolFiles.push(parseSourceFileAst(full, content, rootDir));
      }
    }
  }

  return [...srcFiles, ...toolFiles].sort((a, b) => a.relPath.localeCompare(b.relPath));
}

export function generateArchitectureMap(rootDir: string = process.cwd()): string {
  const files = collectAllArchitectureFiles(rootDir);
  const totalLines = files.reduce((acc, f) => acc + f.lineCount, 0);
  const nearCapFiles = files.filter((f) => f.lineCount >= 240);
  const breachFiles = files.filter((f) => f.lineCount >= 300);
  const avgLines = files.length > 0 ? Math.round(totalLines / files.length) : 0;

  let doc = `# System Architecture Map — Aether & Soot\n\n`;
  doc += `> **AUTO-GENERATED**: Generated by \`tests/scripts/generate-architecture-map.ts\` (\`npm run generate:arch-map\`).\n\n`;
  doc += `## Codebase Telemetry & Modularity Health\n\n`;
  doc += `- **Files Indexed**: ${files.length}\n`;
  doc += `- **Total Lines of Code**: ${totalLines}\n`;
  doc += `- **Average File Size**: ${avgLines} lines (Target: <= 250)\n`;
  doc += `- **Modularity Gate Status**: ${breachFiles.length === 0 ? 'CLEAN (0 files >= 300 lines)' : `BREACH (${breachFiles.length} files >= 300 lines)`}\n`;
  doc += `- **Near-Cap Files (>= 240 lines)**: ${nearCapFiles.length} files\n\n`;

  if (nearCapFiles.length > 0) {
    doc += `### Near-Cap File Watchlist (Approaching 300-Line Ceiling)\n\n`;
    doc += `| File | Lines | Action Required |\n`;
    doc += `| :--- | :---: | :--- |\n`;
    for (const f of nearCapFiles.sort((a, b) => b.lineCount - a.lineCount)) {
      const action = f.lineCount >= 300 ? '**CRITICAL: Split immediately**' : 'Extract sub-module before adding functions';
      doc += `| \`${f.relPath}\` | ${f.lineCount} | ${action} |\n`;
    }
    doc += `\n`;
  }

  for (const group of ARCHITECTURE_GROUPS) {
    const groupFiles = files.filter((f) => group.filter(f.relPath));
    if (groupFiles.length === 0) continue;

    doc += `## ${group.title}\n\n`;
    doc += `${group.description}\n\n`;
    doc += `| File | Lines | Status | Primary Exports & Signatures |\n`;
    doc += `| :--- | :---: | :---: | :--- |\n`;

    for (const f of groupFiles) {
      const status = f.lineCount >= 300 ? '❌ FAIL' : f.lineCount >= 240 ? '⚠️ WARN' : '✅ OK';
      const keyExports = (f.functionSignatures.length > 0 ? f.functionSignatures : f.exports)
        .slice(0, 4)
        .map((s) => `\`${s.replace(/\|/g, '\\|')}\``)
        .join(', ');
      doc += `| \`${f.relPath}\` | ${f.lineCount} | ${status} | ${keyExports || '*None (internal)*'} |\n`;
    }
    doc += `\n`;
  }

  return doc;
}

export function writeArchitectureMap(rootDir: string = process.cwd(), outputPath?: string): string {
  const targetPath = outputPath ?? path.join(rootDir, 'docs/architecture-map.md');
  const content = generateArchitectureMap(rootDir);
  const dir = path.dirname(targetPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(targetPath, content, 'utf-8');
  return targetPath;
}

