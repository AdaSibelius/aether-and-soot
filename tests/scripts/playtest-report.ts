import fs from 'node:fs';
import path from 'node:path';
import { PlaytestScenario } from './playtester-scenarios.js';
import { getConnectionTelemetry, LlmConnectionTelemetry } from './local-llm-config.js';
import { auditCommandCoverage, CommandCoverage } from './critic-report.js';

export interface PlaytestReportConfig {
  readonly mock: boolean;
  readonly maxTurns: number;
  readonly seed: number;
  readonly endpoint: string;
  readonly model: string;
  readonly reportPath: string;
  readonly scenario: PlaytestScenario;
  readonly telemetry?: LlmConnectionTelemetry | undefined;
}

export interface PlaytestMetrics {
  turnsSurvived: number;
  totalDecibels: number;
  alertTransitions: { investigating: number; combat: number };
  steamCloudsDeployed: number;
  trapsTriggered: number;
  hostilesAttacked: number;
  attackHits: number;
  attackMisses: number;
  damageDealt: number;
  damageTaken: number;
  itemsAcquired: number;
  itemsUsed: number;
  transitionsCompleted: number;
  finalBloodPct: number;
  uniqueTilesVisited: number;
  commandHistogram: Record<string, number>;
  causeOfDeath?: string;
  uiProjectionLeaks?: number;
  commandCoverageMatrix?: CommandCoverage;
  promptTokens?: number;
  completionTokens?: number;
  totalDurationMs?: number;
  averageLatencyMs?: number;
  turnsSurvivedPerKiloToken?: number;
  stageDecisions?: { stage1: number; stage2: number; stage3: number };
}

export function writeReport(config: PlaytestReportConfig, metrics: PlaytestMetrics): void {
  const dir = path.dirname(config.reportPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  const rootDir = path.resolve(import.meta.dirname, '../..');
  const coverage = metrics.commandCoverageMatrix ?? auditCommandCoverage(rootDir, metrics.commandHistogram ?? {});
  const totalCommands = coverage.active.length + coverage.dormant.length + coverage.unwired.length;
  const coveragePct = totalCommands > 0 ? Math.round((coverage.active.length / totalCommands) * 100) : 0;

  const telemetry = config.telemetry ?? getConnectionTelemetry({
    mock: config.mock,
    endpoint: config.endpoint,
    model: config.model,
  });

  const executionMode = config.mock
    ? 'Deterministic Mock Agent (playtester-mock.ts) [MOCK_FALLBACK]'
    : `Local LLM (live local model: ${config.model} @ ${config.endpoint}) [LIVE_INFERENCE]`;

  const status = metrics.causeOfDeath ? `DEFEATED (${metrics.causeOfDeath})` : 'SURVIVED';
  const histogramRows = Object.entries(metrics.commandHistogram ?? {})
    .sort((a, b) => b[1] - a[1])
    .map(([cmd, count]) => `| \`${cmd}\` | ${count} |`)
    .join('\n');

  const content = `# Aether & Soot — Headless Autonomous Playtest Report

- **Timestamp**: ${new Date().toISOString()}
- **Execution Mode**: ${executionMode}
- **LLM Telemetry**: Mode: ${telemetry.llmExecutionMode} | Temperature: ${telemetry.temperature} | Enforce JSON Schema: ${telemetry.enforceJsonSchema}
- **Scenario**: **${config.scenario.toUpperCase()}**
- **Seed**: ${config.seed}
- **Survival Status**: **${status}**

## LLM Token & Inference Efficiency

| Metric | Recorded Value | Evaluation Notes |
| :--- | :--- | :--- |
| **Prompt Tokens** | ${metrics.promptTokens ?? 0} | Context tokens sent to local models |
| **Completion Tokens** | ${metrics.completionTokens ?? 0} | Action tokens generated by local models |
| **Total Tokens** | ${(metrics.promptTokens ?? 0) + (metrics.completionTokens ?? 0)} | Aggregated token volume |
| **Average Latency / Turn** | ${metrics.averageLatencyMs ?? 0} ms | Wall-clock execution time per turn |
| **Survival per 1,000 Tokens** | ${metrics.turnsSurvivedPerKiloToken ?? 0} turns/1k tokens | Efficiency of longevity per token |
| **Policy Stage Distribution** | S1 (Reflex): ${metrics.stageDecisions?.stage1 ?? 0} \| S2 (Fast Tier 3): ${metrics.stageDecisions?.stage2 ?? 0} \| S3 (Reasoning Tier 1): ${metrics.stageDecisions?.stage3 ?? 0} | 3-stage hybrid decision distribution |

## Emergent Sandbox Mechanics Metrics

| Metric | Recorded Value | Evaluation Notes |
| :--- | :--- | :--- |
| **Turns Survived** | ${metrics.turnsSurvived} / ${config.maxTurns} | Longevity under autonomous navigation |
| **Acoustic Decibels Emitted** | ${metrics.totalDecibels} dB | Footsteps, door actions, and steam releases |
| **Guard Sound Investigations** | ${metrics.alertTransitions.investigating} | NPCs transitioning to INVESTIGATING |
| **Guard Combat Engagements** | ${metrics.alertTransitions.combat} | NPCs acquiring visual lock in COMBAT |
| **Steam Clouds Deployed** | ${metrics.steamCloudsDeployed} | Vented steam to obscure LOS |
| **Clockwork Traps Triggered** | ${metrics.trapsTriggered} | Hidden tripwires / spring jaws stepped on |
| **Hostiles Attacked** | ${metrics.hostilesAttacked} | Targeted melee / ranged strikes on hostiles |
| **Attack Hits** | ${metrics.attackHits} | Clean strikes landing on target |
| **Attack Misses / Obstructed** | ${metrics.attackMisses} | Evasions, range misses, or deflections |
| **Damage Dealt (Player)** | ${metrics.damageDealt} HP | Targeted combat damage to hostiles |
| **Damage Taken (Player)** | ${metrics.damageTaken} HP | Trauma sustained from hostiles or hazards |
| **Items Acquired** | ${metrics.itemsAcquired} | Picked up from ground or bought from merchants |
| **Items Used** | ${metrics.itemsUsed} | Consumed tonics or canisters |
| **Transitions Completed** | ${metrics.transitionsCompleted} | Stratum portals or district gates traversed |
| **Final Blood Volume** | ${metrics.finalBloodPct}% | Haemodynamic stability |
| **Unique Tiles Visited** | ${metrics.uniqueTilesVisited} | Distinct spatial tiles explored |
| **UI Projection Leaks Detected** | ${metrics.uiProjectionLeaks ?? 0} | Client projection HUD/radar/chronicle leaks |

## Command Coverage Matrix

| Category | Count | Share | Command Identifiers |
| :--- | :--- | :--- | :--- |
| **Active Commands** (>0 Dispatches) | ${coverage.active.length} | ${coveragePct}% | ${coverage.active.map((c) => `\`${c}\``).join(', ') || 'None'} |
| **Dormant Commands** (Serializer-Wired, 0 Dispatches) | ${coverage.dormant.length} | - | ${coverage.dormant.slice(0, 10).map((c) => `\`${c}\``).join(', ') || 'None'} |
| **Unwired Commands** (Missing from Context) | ${coverage.unwired.length} | - | ${coverage.unwired.slice(0, 10).map((c) => `\`${c}\``).join(', ') || 'None'} |

## Client UI Projection & Chronicle Leak Audit

- **Total UI Projection Leaks Detected**: **${metrics.uiProjectionLeaks ?? 0}**
- **Leak Categories Monitored**: Raw snake_case identifiers (\`district_\`, \`landmark_\`, \`npc_\`, \`item_\`, \`mat_\`), truncated strings (\`_\`), coordinate desyncs (LookCursorOverlay vs TileInspectorPanel), and duplicate consecutive chronicle movement entries.
- **Audit Status**: ${(metrics.uiProjectionLeaks ?? 0) === 0 ? 'CLEAN — Zero UI projection leaks detected.' : `WARNING — ${metrics.uiProjectionLeaks} projection anomalies detected.`}

## Command Dispatch Histogram

| Command Type | Dispatches |
| :--- | :--- |
${histogramRows || '| None | 0 |'}
`;

  fs.writeFileSync(config.reportPath, content, 'utf-8');

  // Also write to playtest-report-economy.md when scenario is economy or sabotage
  if (config.scenario === 'economy' || config.scenario === 'sabotage') {
    const economyReportPath = path.resolve(dir, 'playtest-report-economy.md');
    fs.writeFileSync(economyReportPath, content, 'utf-8');
  }
}
